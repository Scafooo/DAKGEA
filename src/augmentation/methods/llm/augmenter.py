# Algorithm 3
# ----------------------------------------------------------------------
class LuffyLGenerator:
    """AugmentAttributes for Luffy-L, with the LLMCache of Algorithm 3.

    ``literals_for(node)`` returns, for each KG side where ``node`` exists, the
    list of (predicate URI, value) to attach to the augmented copy.
    """

    def __init__(self, client: CachedLLMClient, ctx_builder: ContextBuilder,
                 domain: str, use_cache: bool, stats: dict, log_path: Optional[Path] = None):
        self.client = client
        self.ctx = ctx_builder
        self.domain = domain
        self.use_cache = use_cache
        self.stats = stats
        self.log_path = log_path
        # LLMCache: Set-KG node -> side -> predicate -> values (generated by an earlier call)
        self.llm_cache: Dict[URIRef, Dict[str, Dict[URIRef, List[str]]]] = {}
        self.generated: set = set()   # nodes whose literals were already written

    def _log(self, record: dict) -> None:
        if self.log_path is None:
            return
        with open(self.log_path, "a", encoding="utf-8") as fh:
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")

    def _prime(self, ctx, parsed) -> None:
        """foreach neighbour O with generated literals: LLMCache[O] <- (LN[O], {}).

        O is primed only if the call generated ALL its attribute values; otherwise
        (prompt cap or omissions by the model) O gets its own call when visited,
        instead of falling back to original values for the missing ones."""
        for lid, lits in parsed.values.items():
            if lid == "S" or lid not in ctx.neighbors:
                continue
            nb = ctx.neighbors[lid]
            if nb in self.generated:
                continue
            if self._covers_all(nb, lits):
                self.llm_cache[nb] = lits
                self.stats["llm_cache_primed"] += 1
            else:
                self.stats["llm_cache_not_primed_incomplete"] += 1

    def _pending(self, neighbors: List[URIRef]) -> List[URIRef]:
        return [nb for nb in neighbors if nb not in self.generated and nb not in self.llm_cache]

    def _call(self, node: URIRef, chunk: List[URIRef], s_generated):
        """One LLM call for S (+ chunk). Continuation call when ``s_generated`` is given."""
        ctx = self.ctx.build(node, chunk, s_generated=s_generated)
        system = SYSTEM_LUFFY_L if s_generated is None else SYSTEM_LUFFY_L_CONTINUATION
        response = self.client.generate(system, build_user_prompt(ctx, self.domain))
        self.stats["llm_requests"] += 1
        if s_generated is not None:
            self.stats["continuation_requests"] += 1
        self.stats["context_literals_truncated"] += ctx.n_literals_truncated
        parsed = parse_luffy_l(response.text, ctx)
        if parsed is None:
            self.stats["parse_failures"] += 1
        else:
            self.stats["unknown_keys_dropped"] += parsed.n_unknown_keys
            if self.use_cache:
                self._prime(ctx, parsed)
        self._log({"node": str(node), "source": "llm",
                   "kind": "first" if s_generated is None else "continuation",
                   "parsed": parsed is not None, "disk_cache": response.from_cache,
                   "n_neighbors": len(ctx.neighbors)})
        return parsed

    def _continue(self, node: URIRef, generated, chunks: List[List[URIRef]]) -> None:
        if not self.use_cache:
            return
        for chunk in chunks:
            if chunk:
                self._call(node, chunk, generated)

    def _covers_all(self, node: URIRef, lits: Dict[str, Dict[URIRef, List[str]]]) -> bool:
        for side, ent in self.ctx.components(node).items():
            preds = {p for p, _ in self.ctx._literals_of(side, ent)}
            if not preds <= set(lits.get(side, {})):
                return False
        return True

    def literals_for(self, node: URIRef) -> Dict[str, List[Tuple[URIRef, str]]]:
        comps = self.ctx.components(node)
        generated: Optional[Dict[str, Dict[URIRef, List[str]]]] = None

        is_pair = self.ctx.set_graph.is_set_node(node)

        if self.use_cache and node in self.llm_cache:
            generated = self.llm_cache.pop(node)          # (L, LN) <- LLMCache[S]
            self.stats["llm_cache_hits"] += 1
            self._log({"node": str(node), "source": "llm_cache"})
            chunks = []
            if is_pair:
                # Implementation choice (see CLAUDE.md): Algorithm 3 gives a cached S no
                # neighbour literals (LN = {}), so each of its unprimed neighbours would
                # later cost one call. On hubs (ICEWS) that is hundreds of calls per pair.
                # Instead the pending neighbours are generated in continuation calls that
                # receive S's cached values: same coherence goal, a fraction of the calls.
                chunks = self.ctx.chunk_neighbors(self._pending(self.ctx.neighbor_nodes(node)))
            self._continue(node, generated, chunks)
        else:
            # Algorithm 3: one call returns the literals of S and of its neighbours.
            # Neighbours that do not fit one prompt go to continuation calls that receive
            # S's generated values. Without LLMCache (no_cache) only the first call is
            # made, its neighbours serving as context. A singleton S (only reached at the
            # depth limit) gets one call: its own neighbours are never visited by the BFS.
            all_nbs = self.ctx.neighbor_nodes(node)
            if self.use_cache:
                chunks = self.ctx.chunk_neighbors(self._pending(all_nbs)) or [[]]
            else:
                chunks = self.ctx.chunk_neighbors(all_nbs)[:1] or [[]]
            if not is_pair:
                chunks = chunks[:1]
            first = self._call(node, chunks[0], None)
            generated = first.values.get("S") if first is not None else None
            generated = generated or None
            if generated is not None:
                self._continue(node, generated, chunks[1:])

        self.generated.add(node)
        out: Dict[str, List[Tuple[URIRef, str]]] = {}
        for side, ent in comps.items():
            originals: Dict[URIRef, List[str]] = {}
            for p, v in self.ctx._literals_of(side, ent):
                originals.setdefault(p, []).append(v)
            gen_side = (generated or {}).get(side, {})
            values: List[Tuple[URIRef, str]] = []
            for p, orig_vals in originals.items():
                new_vals = gen_side.get(p)
                if new_vals:
                    values.extend((p, v) for v in new_vals[: len(orig_vals)])
                    self.stats["values_generated"] += min(len(new_vals), len(orig_vals))
                    self.stats["values_identical_to_original"] += sum(
                        1 for v in new_vals[: len(orig_vals)] if v in orig_vals)
                else:
                    # Paper: unparseable / missing output -> keep the original value
                    values.extend((p, v) for v in orig_vals)
                    self.stats["values_fallback_original"] += len(orig_vals)
            out[side] = values
        return out


