"""Luffy-L: LLM instantiation of AugmentAttributes (paper, Algorithm 3).

Design rule: structural replication is NOT reimplemented here. ``LLMAugmenter``
subclasses ``PLMAugmenter`` (the class Luffy-S uses) and inherits, unchanged:

* the Set-KG construction (``SetKnowledgeGraph.from_dataset``),
* the BFS traversal, seed order, depth limit and budget
  (``_bfs_expansion``, ``_process_neighbors``, ``_compute_pair_budget`` ...),
* the creation of augmented relations (edges towards O_aug).

Only the two places where Luffy-S generates literal values are replaced:

* matched set-entities: ``NodeExpander.bootstrap_literals``  -> ``LuffyLGenerator``
* singleton neighbours: ``PLMAugmenter._expand_non_set_node`` -> ``LuffyLGenerator``

Variants (``augmentation.variant``, required):
  full      Algorithm 1 + Algorithm 3 with LLMCache
  no_cache  LLMCache disabled: every visited entity gets its own call
  no_bfs    no neighbourhood expansion (``max_depth = 0``)
  all_llm   ablation without scaffold: one call per sampled training pair,
            the model writes the whole synthetic pair (attributes + relations),
            restricted to the input alphabet (no new entities/predicates/relations)
"""

