class _SortedNeighborHandler(NeighborHandler):
    """Same neighbours as Luffy-S, in a deterministic order.

    The DAKGEA loaders fill the graphs from Python sets, so the triple order (and
    therefore the BFS order) changes with PYTHONHASHSEED from one process to the
    next. Luffy-L needs the same traversal in every run of a seed (af prefixes,
    cache replay), so neighbours are sorted by (predicate, neighbour)."""

    _MEMO_SIZE = 4096

    def __init__(self):
        super().__init__()
        # (graph id, node) -> sorted neighbours. The Set-KG is never modified during the
        # BFS; the scaffold asks for the same node several times (logging, bridging).
        self._memo: "OrderedDict" = OrderedDict()

    def iter_neighbors(self, graph, node):
        key = (id(graph), node)
        items = self._memo.get(key)
        if items is not None:
            self._memo.move_to_end(key)
        else:
            outgoing = sorted(((p, o) for _, p, o in graph.triples((node, None, None))),
                              key=lambda t: (str(t[0]), str(t[1])))
            incoming = sorted(((p, s) for s, p, _ in graph.triples((None, None, node))),
                              key=lambda t: (str(t[0]), str(t[1])))
            items = [("out", p, o) for p, o in outgoing] + [("in", p, s) for p, s in incoming]
            self._memo[key] = items
            if len(self._memo) > self._MEMO_SIZE:
                self._memo.popitem(last=False)
        return iter(items)


class _NoCopyNeighborHandler(_SortedNeighborHandler):
    """Drops the verbatim copy of original literals onto augmented entities."""

    def attach_literal_to_augmented(self, *args, **kwargs) -> None:
        return None


class LLMNodeExpander(NodeExpander):
    """NodeExpander whose literal generation is Algorithm 3."""

    def __init__(self, derived_predicate, add_derived_predicate, generator: LuffyLGenerator):
        super().__init__(derived_predicate, add_derived_predicate, None, {}, None,
                         value_consistency_config={})
        self.generator = generator
        self._current_node: Optional[URIRef] = None

    def expand_set_node(self, dataset, set_graph, set_node):
        self._current_node = set_node      # remembered for bootstrap_literals below
        return super().expand_set_node(dataset, set_graph, set_node)

    def bootstrap_literals(self, dataset, src_component, tgt_component, src_aug, tgt_aug) -> None:
        lits = self.generator.literals_for(self._current_node)
        for p, v in lits.get("KG1", []):
            dataset.knowledge_graph_source.add((src_aug, p, Literal(v)))
        for p, v in lits.get("KG2", []):
            dataset.knowledge_graph_target.add((tgt_aug, p, Literal(v)))


@AUGMENTATION_REGISTRY.register("llm")
class LLMAugmenter(PLMAugmenter):
    registry_name = "llm_augmentation"
    _LLM_DEFAULT_CONFIG = "config/augmentation/llm.yaml"

    def __init__(self, config: Optional[dict] = None):
        super().__init__(config)
        aug = self.config.get("augmentation", {})
        llm_defaults = {}
        default_path = PROJECT_ROOT / self._LLM_DEFAULT_CONFIG
        if default_path.exists():
            llm_defaults = (yaml.safe_load(default_path.read_text()) or {}).get("augmentation", {})

        self.variant = aug.get("variant")
        if self.variant not in VARIANTS:
            raise ValueError(f"augmentation.variant must be one of {VARIANTS}, got {self.variant!r}")
        if "copy_original_literals" not in aug:
            raise ValueError(
                "augmentation.copy_original_literals is required (true = same as the Luffy-S "
                "runs, which copy every original literal onto the augmented entities; "
                "false = paper behaviour). Decide it explicitly."
            )
        self.copy_original_literals = bool(aug["copy_original_literals"])
        self.llm_cfg = {**llm_defaults.get("llm", {}), **aug.get("llm", {})}
        self.prompt_cfg = {**llm_defaults.get("prompt", {}), **aug.get("prompt", {})}
        self.max_depth = int(aug.get("max_depth", llm_defaults.get("max_depth", 2)))
        if self.variant == "no_bfs":
            self.max_depth = 0
        self.neighbor_handler = (_SortedNeighborHandler() if self.copy_original_literals
                                 else _NoCopyNeighborHandler())

        exp = self.config.get("experiment", {})
        ds = exp.get("dataset", "")
        self.dataset_name = ds.get("name", "") if isinstance(ds, dict) else str(ds)
        self.stage_root = Path(aug["stage_root"]) if aug.get("stage_root") else None
        self.mock_fn = None   # tests inject an offline backend here
        self.stats = {k: 0 for k in (
            "llm_requests", "llm_cache_hits", "llm_cache_primed", "llm_cache_not_primed_incomplete",
            "continuation_requests",
            "parse_failures",
            "unknown_keys_dropped", "values_generated", "values_fallback_original",
            "values_identical_to_original", "context_literals_truncated", "pairs_failed", "out_of_alphabet_dropped",
        )}

    # ------------------------------------------------------------------
    def _make_client(self) -> CachedLLMClient:
        cfg = dict(self.llm_cfg)
        cache_path = Path(cfg["cache_path"])
        cfg["cache_path"] = str(cache_path if cache_path.is_absolute() else PROJECT_ROOT / cache_path)
        return build_client(cfg, self.seed, mock_fn=self.mock_fn)

    def _ctx_builder(self, dataset: Dataset, set_graph: SetKnowledgeGraph) -> ContextBuilder:
        c = self.prompt_cfg
        return ContextBuilder(
            dataset, set_graph,
            max_neighbors=int(c.get("max_neighbors", 40)),
            max_neighbor_values=int(c.get("max_neighbor_values", 120)),
            max_literals_target=int(c.get("max_literals_target", 100)),
            max_literals_neighbor=int(c.get("max_literals_neighbor", 30)),
            max_relations=int(c.get("max_relations", 60)),
            max_value_chars=int(c.get("max_value_chars", 300)),
            max_value_chars_neighbor=int(c.get("max_value_chars_neighbor", 150)),
        )

    def _write_stats(self, client: CachedLLMClient, initial_pairs: int, budget, expanded: int) -> None:
        payload = {
            "variant": self.variant, "seed": self.seed, "dataset": self.dataset_name,
            "copy_original_literals": self.copy_original_literals, "max_depth": self.max_depth,
            "initial_pairs": initial_pairs, "pair_budget": budget, "pairs_augmented": expanded,
            "api_calls": client.n_api_calls, "disk_cache_hits": client.n_disk_hits,
            "input_tokens": client.input_tokens, "output_tokens": client.output_tokens,
            "truncated_outputs": client.n_truncated_outputs,
            "llm": {k: v for k, v in self.llm_cfg.items() if k != "cache_path"},
            "prompt": self.prompt_cfg, **self.stats,
        }
        self.logger.info("[LUFFY-L] stats: %s", json.dumps(payload))
        if self.stage_root:
            self.stage_root.mkdir(parents=True, exist_ok=True)
            (self.stage_root / "luffy_l_stats.json").write_text(json.dumps(payload, indent=2))

    # ------------------------------------------------------------------
    def augment(self, dataset: Dataset) -> Dataset:
        initial_pairs = len(dataset.aligned_entities)
        out = dataset.clone()
        if not dataset.aligned_entities:
            return out

        set_graph = SetKnowledgeGraph.from_dataset(out)
        ctx_builder = self._ctx_builder(out, set_graph)
        client = self._make_client()
        budget = self._compute_pair_budget(initial_pairs)
        log_path = (self.stage_root / "luffy_l_calls.jsonl") if self.stage_root else None
        if log_path:
            log_path.parent.mkdir(parents=True, exist_ok=True)

        if self.variant == "all_llm":
            expanded = self._augment_all_llm(out, set_graph, ctx_builder, client, budget)
        else:
            generator = LuffyLGenerator(
                client, ctx_builder, domain_for(self.dataset_name),
                use_cache=(self.variant != "no_cache"), stats=self.stats, log_path=log_path,
            )
            self.node_expander = LLMNodeExpander(
                self.derived_predicate, self.add_derived_predicate, generator)
            self._generator = generator
            set_nodes = sorted(set_graph.iter_set_nodes(), key=lambda uri: str(uri))
            random.Random(self.seed).shuffle(set_nodes)      # same seed order as Luffy-S
            self._log_augmentation_start(initial_pairs, budget)
            expanded = self._bfs_expansion(out, set_graph, set_nodes, budget)

        self._write_stats(client, initial_pairs, budget, expanded)
        return out

    # Singletons (|O| = 1): same URI minting and edges as Luffy-S, literals from Algorithm 3
    def _expand_non_set_node(self, dataset, set_graph, non_set_node):
        aug_counter = getattr(self, "_non_set_aug_counter", 0)
        self._non_set_aug_counter = aug_counter + 1
        in_source = self.neighbor_handler._node_in_graph(dataset.knowledge_graph_source, non_set_node)
        in_target = self.neighbor_handler._node_in_graph(dataset.knowledge_graph_target, non_set_node)
        src_aug = URIRef(f"{non_set_node}_aug{aug_counter}") if in_source else None
        tgt_aug = URIRef(f"{non_set_node}_aug{aug_counter + 1}") if in_target else None

        lits = self._generator.literals_for(non_set_node)
        if src_aug is not None:
            for p, v in lits.get("KG1", []):
                dataset.knowledge_graph_source.add((src_aug, p, Literal(v)))
        if tgt_aug is not None:
            for p, v in lits.get("KG2", []):
                dataset.knowledge_graph_target.add((tgt_aug, p, Literal(v)))
        return src_aug, tgt_aug

    # ------------------------------------------------------------------
    # all_llm ablation: no Set-KG traversal, no cache, the LLM writes the pair
    # ------------------------------------------------------------------
    def _augment_all_llm(self, out: Dataset, set_graph: SetKnowledgeGraph,
                         ctx_builder: ContextBuilder, client: CachedLLMClient, budget) -> int:
        pairs = sorted(set_graph.iter_set_nodes(), key=lambda uri: str(uri))
        random.Random(self.seed).shuffle(pairs)
        if budget is not None:
            pairs = pairs[:budget]
        domain = domain_for(self.dataset_name)
        kgs = {"KG1": out.knowledge_graph_source, "KG2": out.knowledge_graph_target}
        alignments = list(out.aligned_entities)
        counter = 0
        created = 0
        log_path = (self.stage_root / "luffy_l_calls.jsonl") if self.stage_root else None

        for node in pairs:
            ctx: PromptContext = ctx_builder.build(node)
            response = client.generate(SYSTEM_ALL_LLM, build_user_prompt(ctx, domain))
            self.stats["llm_requests"] += 1
            parsed = parse_all_llm(response.text, ctx)
            ok = parsed is not None and any(parsed.attributes.get(s) for s in ctx.sides)
            if log_path:
                with open(log_path, "a", encoding="utf-8") as fh:
                    fh.write(json.dumps({"node": str(node), "ok": ok,
                                         "disk_cache": response.from_cache}) + "\n")
            if not ok:
                self.stats["parse_failures" if parsed is None else "pairs_failed"] += 1
                continue                                   # no fallback in all_llm
            self.stats["out_of_alphabet_dropped"] += parsed.n_out_of_alphabet

            aug = {}
            for side, view in ctx.sides.items():
                counter += 1
                aug[side] = URIRef(f"{view.entity}_aug{counter}")
                for p, vals in parsed.attributes.get(side, {}).items():
                    for v in vals:
                        kgs[side].add((aug[side], p, Literal(v)))
                    self.stats["values_generated"] += len(vals)
                if self.copy_original_literals:
                    # same verbatim copy the Luffy-S scaffold performs on set-entities
                    for other in SIDES:
                        if other in ctx.sides:
                            for p, v in ctx_builder._literals_of(other, ctx.sides[other].entity):
                                kgs[side].add((aug[side], p, Literal(v)))
                for rel, direction, lid in parsed.relations.get(side, []):
                    target = ctx_builder.components(ctx.neighbors[lid]).get(side)
                    if target is None:
                        self.stats["out_of_alphabet_dropped"] += 1
                        continue
                    if direction == "->":
                        kgs[side].add((aug[side], rel, target))
                    else:
                        kgs[side].add((target, rel, aug[side]))
            alignments.append((str(aug["KG1"]), str(aug["KG2"])))
            created += 1

        out.aligned_entities = tuple(alignments)
        return created
